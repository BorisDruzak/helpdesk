import { expect, test } from "playwright/test";
import { installStudioV3Fixture } from "./fixtures/studio-v3";

for (const width of [1366,1920]) test(`publication metadata and terminal SLA ${width}`, async ({ page }, info) => {
  await page.setViewportSize({width,height:width===1366?768:1080});
  const state=await installStudioV3Fixture(page);
  state.definition().schema_version=4; state.definition().execution_semantics=3;
  await page.route("**/api/web/notifications/push/config",r=>r.fulfill({json:{status:"ok",enabled:false,public_key:null}}));
  await page.route("**/request-studio/fragments",r=>r.fulfill({json:{status:"success",data:{items:[],total:0}}}));
  await page.goto("/app/admin/request-template-studio");
  await page.getByRole("button",{name:"Настроить услугу Проблемы с печатью",exact:true}).dblclick();
  await page.getByRole("button",{name:"Опубликовать",exact:true}).click();
  await page.getByRole("button",{name:"Настройки услуги",exact:true}).click();
  await page.getByText("Раздел и категория",{exact:true}).click();
  await expect(page.getByRole("combobox",{name:"Раздел каталога",exact:true})).toBeVisible();
  await page.getByRole("button",{name:"Вернуться к карте",exact:true}).click();
  await expect(page.locator('[data-scenario-edge="studio:entry-point:special"]')).toBeVisible();
  await page.getByRole("list",{name:"Блоки сценария",exact:true}).getByRole("button",{name:"Передать в поддержку",exact:true}).click();
  await page.locator('[data-id="end"]').getByRole("button",{name:"Редактировать",exact:true}).click();
  await page.getByRole("button",{name:"Развернуть редактор",exact:true}).click();
  const final=page.getByRole("region",{name:"SLA завершения",exact:true});
  await expect(final).toBeVisible();
  await expect(final).toContainText("Срочный");
  await expect(final).toContainText("Стандартный");
  const choice=final.getByRole("combobox",{name:"SLA при создании обращения",exact:true});
  await choice.selectOption("urgent");
  await expect(final).toContainText("Итоговое назначение: Срочный");
  await expect(final).toContainText("решение: 120 мин.");
  await expect.poll(()=>{const b=state.definition().blocks!.find(b=>b.id==="end")!;return b.kind==="submit_ticket"?b.sla_profile:undefined;}).toBe("urgent");
  await page.screenshot({path:info.outputPath(`terminal-sla-${width}.png`),fullPage:true});
  await choice.selectOption("");
  await expect.poll(()=>Object.hasOwn(state.definition().blocks!.find(b=>b.id==="end")!,"sla_profile")).toBe(false);
  await page.getByRole("button",{name:"Вернуться к карте",exact:true}).click();
  await page.getByRole("button",{name:"Тестировать",exact:true}).click();
  await page.getByRole("button",{name:"Начать проверку",exact:true}).click();
  await page.getByRole("radio",{name:"Принтер",exact:true}).check();
  await page.getByRole("button",{name:"Продолжить проверку",exact:true}).click();
  await page.getByRole("radio",{name:"Весь отдел",exact:true}).check();
  await page.getByRole("button",{name:"Продолжить проверку",exact:true}).click();
  await page.getByRole("radio",{name:"Нет",exact:true}).check();
  await page.getByRole("button",{name:"Продолжить проверку",exact:true}).click();
  await expect(page.getByRole("region",{name:"Результат серверной проверки обработки",exact:true})).toContainText("120 мин.");
  await page.getByRole("button",{name:"Закрыть панель",exact:true}).click();
  await expect(page.locator('[data-id="end"] [aria-label="Итог завершения"]')).toContainText("SLA проверенного пути");
  await expect(page.locator('[data-id="end"] [aria-label="Итог завершения"]')).toContainText("Поддержка печати");
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await expect(page.getByRole("button",{name:"Сохранить черновик",exact:true})).toBeInViewport();
  await page.screenshot({path:info.outputPath(`terminal-path-${width}.png`),fullPage:true});
  expect(state.errors).toEqual([]);expect(state.unexpected).toEqual([]);
});
